if (!existsSync(cefrPath)) {
  console.error("Missing CEFR file:", cefrPath);
  console.error("Download fr-A1.json first.");
  process.exit(1);
}

const cefr = JSON.parse(readFileSync(cefrPath, "utf8"));
const byLemma = new Map();
for (const row of cefr) {
  const lemma = String(row.lemma || "").trim();
  if (!lemma) continue;
  const key = lemma.toLowerCase();
  if (!byLemma.has(key)) byLemma.set(key, row);
}

const entries = [];
const lemmas = [];
const seen = new Set();

for (const [key, glossRaw] of Object.entries(GLOSS)) {
  const gloss = String(glossRaw || "").trim();
  if (!gloss) continue;
  const row = byLemma.get(key);
  const lemma = row?.lemma || key;
  const id = lemma.toLowerCase();
  if (seen.has(id)) continue;
  seen.add(id);
  lemmas.push(lemma);
  /** @type {{ lemma: string, display: string, senses: { pos: string, gloss: string }[], ipa?: string }} */
  const entry = {
    lemma,
    display: lemma,
    senses: [{ pos: row?.pos || "other", gloss }],
  };
  if (row?.ipa) entry.ipa = row.ipa;
  entries.push(entry);
}

const pack = {
  manifest: {
    id: "fr-core-a1-zh",
    title: "法语 A1 核心",
    version: "1.0.0",
    lang: "fr",
    glossLang: "zh",
    source: "official",
    lemmaCount: lemmas.length,
    description: "法语入门核心词 · 中文释义（CEFR A1）",
  },
  lemmas,
  entries,
  phrases: [],
};

const targets = [
  join(root, "fr-core-a1-zh-v1.json"),
  join(root, "_release-upload", "fr-core-a1-zh-v1.json"),
  join(root, "..", "bubtype-wordbooks", "fr-core-a1-zh-v1.json"),
  join(root, "..", "lingoat", "samples", "wordbooks", "fr-core-a1-zh-v1.json"),
];

const json = `${JSON.stringify(pack)}\n`;
for (const path of targets) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, json);
  console.log("wrote", path, "lemmas", lemmas.length);
}
